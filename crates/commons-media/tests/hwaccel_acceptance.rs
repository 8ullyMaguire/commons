//! T-P2-005 acceptance, run against a real ffmpeg and a real GPU device.
//!
//! The unit tests in `hwaccel_plan` prove the *arguments* are coherent. These
//! prove ffmpeg *accepts* them, which is a different claim: `scale_vaapi` looks
//! right in a string and still fails if the driver is not what the filter wants.
//!
//! This machine has `/dev/dri/renderD128` (a real render node) and a build of
//! ffmpeg that lists `vaapi`, so a VA-API plan can actually be attempted here.
//! When there is no device the hardware cases skip *and say so*; the software
//! cases always run, so the suite is never silently empty.

use std::path::Path;
use std::process::Command;

use commons_media::hwaccel::{detect, Accel, HwAccelConfig};
use commons_media::hwaccel_plan::{AccelPlan, Planner, SourceKind};
use commons_media::probe::MediaInfo;
use commons_media::thumbs::{Generator, Kind};

/// A generator pointed at the real ffmpeg, with a given plan.
///
/// `with_binaries` is an associated function that builds its own unlimited
/// budget, so the helper takes only the plan. Writing that construction out at
/// every call site is how a test ends up asserting against a generator that
/// was never pointed at anything.
fn generator_with(plan: AccelPlan) -> Generator {
    Generator::with_binaries(ffmpeg(), "ffprobe").with_plan(plan)
}

fn ffmpeg() -> std::path::PathBuf {
    // The same binary the rest of the test suite uses.
    std::env::var("COMMONS_FFMPEG")
        .map(Into::into)
        .unwrap_or_else(|_| "ffmpeg".into())
}

fn skip_without(reason: &str) {
    eprintln!("SKIPPED: {reason}");
}

fn has_hardware() -> bool {
    let status = detect(Path::new(&ffmpeg()), &HwAccelConfig::default());
    status.available.iter().any(|a| a == "vaapi" || a == "qsv")
}

/// The plan this machine would actually use for a video.
fn hw_plan() -> AccelPlan {
    Planner::detect(Path::new(&ffmpeg()), &HwAccelConfig::default())
        .plan_for_source(SourceKind::Video)
}

/// A real short H.264 video, generated by ffmpeg rather than committed, so the
/// decode path is genuinely exercised.
fn make_video(dir: &Path, seconds: u32) -> std::path::PathBuf {
    let out = dir.join("source.mp4");
    let status = Command::new(ffmpeg())
        .args([
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-f",
            "lavfi",
            "-i",
            &format!("testsrc=size=320x240:rate=10:duration={seconds}"),
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            out.to_str().unwrap(),
        ])
        .status();
    assert!(
        status.map(|s| s.success()).unwrap_or(false),
        "could not build a test video"
    );
    out
}

fn info(duration_ms: u64) -> MediaInfo {
    MediaInfo {
        duration_ms,
        ..Default::default()
    }
}

