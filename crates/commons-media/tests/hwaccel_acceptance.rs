/// **Accept:** a software plan produces the artifact, and the flags are exactly
/// what the pipeline used before acceleration existed.
///
/// "Exactly" matters: if the software path drifted while acceleration was being
/// added, every existing thumbnail would change and the regression would be
/// blamed on ffmpeg.
#[test]
fn a_software_plan_produces_the_artifact_unchanged() {
    let dir = tempfile::tempdir().unwrap();
    let source = make_video(dir.path(), 1);
    let out = dir.path().join("thumb.webp");

    let g = generator_with(AccelPlan::Software);
    assert_eq!(
        *g.plan(),
        AccelPlan::Software,
        "the default must be software"
    );
    let result = g.generate(&source, &out, Kind::Thumbnail { width: 120 }, &info(1000));
    assert!(
        matches!(result, commons_media::thumbs::Generated::Wrote(_)),
        "{result:?}"
    );
    assert!(out.exists());
    let bytes = std::fs::metadata(&out).unwrap().len();
    assert!(bytes > 0, "wrote an empty file");
    // It really is a WebP: `RIFF`....`WEBP`.
    let head = std::fs::read(&out).unwrap();
    assert_eq!(&head[0..4], b"RIFF");
    assert_eq!(&head[8..12], b"WEBP");
}

/// The same file from the software and hardware plans must both be valid
/// WebP, and the software one must be reproducible.
///
/// This is the alpha guarantee: `-pix_fmt yuva420p` has to survive the encoder
/// being sourced from a plan instead of a literal.
#[test]
fn both_plans_produce_the_same_format() {
    let dir = tempfile::tempdir().unwrap();
    let source = make_video(dir.path(), 1);
    let media = info(1000);

    let gen = || generator_with(AccelPlan::Software);

    let sw_out = dir.path().join("sw.webp");
    let a = gen().with_plan(AccelPlan::Software).generate(
        &source,
        &sw_out,
        Kind::Thumbnail { width: 120 },
        &media,
    );
    assert!(
        matches!(a, commons_media::thumbs::Generated::Wrote(_)),
        "{a:?}"
    );

    if !has_hardware() {
        skip_without("no VA-API or QSV device on this machine");
        return;
    }

    let hw_plan = hw_plan();
    assert!(
        hw_plan.is_hardware(),
        "the device is there; the plan should use it"
    );

    let hw_out = dir.path().join("hw.webp");
    let b = gen().with_plan(hw_plan.clone()).generate(
        &source,
        &hw_out,
        Kind::Thumbnail { width: 120 },
        &media,
    );
    assert!(
        matches!(b, commons_media::thumbs::Generated::Wrote(_)),
        "the hardware plan {hw_plan} was rejected by ffmpeg: {b:?}"
    );
    let head = std::fs::read(&hw_out).unwrap();
    assert_eq!(&head[0..4], b"RIFF", "hardware output is not RIFF");
    assert_eq!(&head[8..12], b"WEBP", "hardware output is not WebP");
}

