/// All three kinds, under every plan this machine can build, must all succeed
/// or all fail for a reason that is not "no such filter".
///
/// The failure mode this catches is a plan whose *decode* flags are fine and
/// whose *filter* names a filter ffmpeg does not have -- `scale_nvenc` does not
/// exist, and it would fail on a machine with a perfectly good NVENC card.
#[test]
fn every_kind_works_under_every_usable_plan() {
    let dir = tempfile::tempdir().unwrap();
    let source = make_video(dir.path(), 2);
    let media = info(2000);
    let planner = Planner::detect(Path::new(&ffmpeg()), &HwAccelConfig::default());

    let mut plans = vec![AccelPlan::Software];
    if has_hardware() {
        plans.push(planner.plan_for_source(SourceKind::Video));
    }

    for (i, plan) in plans.iter().enumerate() {
        let gen = generator_with(plan.clone());
        for (j, kind) in [
            Kind::Thumbnail { width: 120 },
            Kind::Marker {
                width: 120,
                at_ms: 500,
            },
            Kind::Sprite {
                width: 100,
                frames: 4,
            },
        ]
        .iter()
        .enumerate()
        {
            let out = dir.path().join(format!("p{i}_k{j}.webp"));
            let result = gen.generate(&source, &out, *kind, &media);
            if let commons_media::thumbs::Generated::Failed(e) = &result {
                let text = format!("{e}");
                assert!(
                    !text.contains("No such filter"),
                    "{plan} rejected {kind:?} with a missing filter: {text}"
                );
                assert!(
                    !text.contains("Impossible to convert"),
                    "{plan} produced an incoherent pixel-format chain for {kind:?}: {text}"
                );
                assert!(
                    !text.contains("Invalid argument"),
                    "{plan} emitted an argument ffmpeg rejected for {kind:?}: {text}"
                );
            }
            assert!(
                matches!(result, commons_media::thumbs::Generated::Wrote(_)),
                "{plan} failed on {kind:?}: {result:?}"
            );
        }
    }
}

/// A sprite under a hardware plan must still have the requested frame count and
/// width. The scale filter is the thing that changed, so the geometry is the
/// thing most likely to be wrong.
#[test]
fn a_hardware_sprite_keeps_the_requested_geometry() {
    let dir = tempfile::tempdir().unwrap();
    let source = make_video(dir.path(), 2);
    let media = info(2000);

    let (frames, width) = (4u32, 100u32);
    let probe = |path: &Path| -> (u32, u32) {
        let out = Command::new("ffprobe")
            .args([
                "-v",
                "error",
                "-select_streams",
                "v:0",
                "-show_entries",
                "stream=width,height",
                "-of",
                "csv=p=0",
                path.to_str().unwrap(),
            ])
            .output()
            .expect("ffprobe");
        let s = String::from_utf8_lossy(&out.stdout);
        let (w, h) = s.trim().split_once(',').expect("dimensions");
        (w.trim().parse().unwrap(), h.trim().parse().unwrap())
    };

    let sw_out = dir.path().join("sw.webp");
    generator_with(AccelPlan::Software).generate(
        &source,
        &sw_out,
        Kind::Sprite { width, frames },
        &media,
    );
    let (sw_w, _) = probe(&sw_out);
    assert_eq!(
        sw_w,
        width * frames,
        "the software sprite is not {frames}x{width}"
    );

    if !has_hardware() {
        skip_without("no VA-API or QSV device on this machine");
        return;
    }
    let hw_plan = hw_plan();
    let hw_out = dir.path().join("hw.webp");
    let result =
        generator_with(hw_plan).generate(&source, &hw_out, Kind::Sprite { width, frames }, &media);
    assert!(
        matches!(result, commons_media::thumbs::Generated::Wrote(_)),
        "{result:?}"
    );
    let (hw_w, _) = probe(&hw_out);
    assert_eq!(
        hw_w,
        width * frames,
        "the hardware sprite is {hw_w} wide, expected {}",
        width * frames
    );
}

