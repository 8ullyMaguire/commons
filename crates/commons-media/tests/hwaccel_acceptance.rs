/// The status is complete and actionable on this machine, and the plan the
/// settings page would offer actually matches the plan that works.
#[test]
fn the_reported_status_and_the_plan_agree() {
    let status = detect(Path::new(&ffmpeg()), &HwAccelConfig::default());
    status
        .is_actionable()
        .unwrap_or_else(|e| panic!("{e}: {}", status.summary()));

    let planner = Planner::new(status.clone(), &HwAccelConfig::default());
    let plan = planner.plan_for_source(SourceKind::Video);
    if let Some(accel) = plan.accel() {
        assert!(
            status.has(accel),
            "the plan chose {accel} but the status does not list it as available: {}",
            status.summary()
        );
    } else {
        // Declined: there must be a reason, and it must be one of the real
        // causes, not a shrug.
        let reason = planner
            .declined_reason(SourceKind::Video)
            .expect("a declined plan must say why");
        assert!(reason.len() > 20, "{reason:?}");
    }
    // Every accelerator the status knows about is a real one.
    for name in &status.available {
        assert!(Accel::parse(name).is_some(), "{name} is not an Accel");
    }
}

/// Report-only must not change what gets produced, only what the status says.
///
/// #7007: the Docker image runs unprivileged, so the default there is to
/// report rather than to use. If report-only also silently dropped the flags
/// in a way that changed the output, the two would not be interchangeable.
#[test]
fn report_only_reports_and_does_not_accelerate() {
    let dir = tempfile::tempdir().unwrap();
    let source = make_video(dir.path(), 1);
    let media = info(1000);
    let config = HwAccelConfig {
        disabled: vec![],
        report_only: true,
    };
    let planner = Planner::detect(Path::new(&ffmpeg()), &config);
    let plan = planner.plan_for_source(SourceKind::Video);
    assert_eq!(
        plan,
        AccelPlan::Software,
        "report-only must not produce a hardware plan"
    );
    // But the *status* still knows what is out there, which is the point.
    let status = planner.status();
    if !status.available.is_empty() {
        assert!(
            status.unavailable.iter().all(|(_, r)| !r.is_empty()),
            "report-only status has an empty reason: {}",
            status.summary()
        );
    }
    // And the artifact still gets made.
    let out = dir.path().join("t.webp");
    let r = generator_with(plan).generate(&source, &out, Kind::Thumbnail { width: 120 }, &media);
    assert!(
        matches!(r, commons_media::thumbs::Generated::Wrote(_)),
        "{r:?}"
    );
}

/// A disabled accelerator produces a software plan even with the hardware
/// present, and the artifact is unchanged.
#[test]
fn a_disabled_accelerator_produces_the_same_bytes_as_no_accelerator() {
    let dir = tempfile::tempdir().unwrap();
    let source = make_video(dir.path(), 1);
    let media = info(1000);

    let none_out = dir.path().join("none.webp");
    generator_with(AccelPlan::Software).generate(
        &source,
        &none_out,
        Kind::Thumbnail { width: 120 },
        &media,
    );

    let config = HwAccelConfig {
        disabled: Accel::ALL.to_vec(),
        report_only: false,
    };
    let plan = Planner::detect(Path::new(&ffmpeg()), &config).plan_for_source(SourceKind::Video);
    assert_eq!(plan, AccelPlan::Software);

    let off_out = dir.path().join("off.webp");
    generator_with(plan).generate(&source, &off_out, Kind::Thumbnail { width: 120 }, &media);

    assert_eq!(
        std::fs::read(&none_out).unwrap(),
        std::fs::read(&off_out).unwrap(),
        "switching acceleration off changed the output bytes"
    );
}
